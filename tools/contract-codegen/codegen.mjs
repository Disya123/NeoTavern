/**
 * Map a property schema to its Rust type. Inline (non-$id) objects become named
 * helper structs (`Pascal(parentId) + PascalField(key)`), collected into `helpers`
 * in first-use order so emission stays deterministic.
 */
function rustTypeFor(schema, ctx, suggestedName) {
  if (schema === null || typeof schema !== 'object') {
    throw new Error(`rustType: expected a schema object, got ${String(schema)}`);
  }
  if (typeof schema.$id === 'string') {
    if (ctx.registryIds.has(schema.$id)) return pascalOfId(schema.$id);
    throw new Error(`rustType: property references unknown $id "${schema.$id}"`);
  }
  if (Array.isArray(schema.anyOf)) {
    if (schema.anyOf.every(isStringConst)) return 'String';
    throw new Error(
      `rustType: inline anyOf that is not a closed string enum cannot be typed: ${canonicalString(schema)}`,
    );
  }
  switch (schema.type) {
    case 'string':
      return 'String';
    case 'integer':
      return 'i64';
    case 'number':
      return 'f64';
    case 'boolean':
      return 'bool';
    case 'null':
      return 'Value';
    case 'object': {
      const keys = Object.keys(schema.properties ?? {});
      const ap = schema.additionalProperties;
      if (keys.length === 0) {
        if (ap === true) return 'Value';
        if (ap !== null && typeof ap === 'object') {
          return `HashMap<String, ${rustPrimitiveType(ap)}>`;
        }
        throw new Error(
          `rustType: empty strict object without $id cannot be typed: ${canonicalString(schema)}`,
        );
      }
      return helperFor(schema, suggestedName, ctx);
    }
    case 'array': {
      const items = schema.items;
      if (items === null || typeof items !== 'object') {
        throw new Error(`rustType: array without an items schema: ${canonicalString(schema)}`);
      }
      return `Vec<${rustTypeFor(items, ctx, suggestedName)}>`;
    }
    default:
      throw new Error(`rustType: unsupported schema: ${canonicalString(schema)}`);
  }
}

function rustPrimitiveType(schema) {
  if (schema === null || typeof schema !== 'object') {
    throw new Error(`rustPrimitiveType: expected a schema object, got ${String(schema)}`);
  }
  switch (schema.type) {
    case 'string':
      return 'String';
    case 'integer':
      return 'i64';
    case 'number':
      return 'f64';
    case 'boolean':
      return 'bool';
    default:
      throw new Error(
        `rustPrimitiveType: unsupported map value schema: ${canonicalString(schema)}`,
      );
  }
}

function helperFor(schema, suggestedName, ctx) {
  if (typeof suggestedName !== 'string' || suggestedName.length === 0) {
    throw new Error('helperFor: inline object needs a contextual type name');
  }
  const typeName = suggestedName;
  // Only the struct is emitted: property checks inline the object logic (helpers have no
  // registered $id, so per §3 there is no check_<child> delegation), and emitting an
  // unused checker would trip rustc's dead_code lint.
  ctx.helpers.push({ typeName, structLines: emitStructLines(schema, typeName, ctx) });
  return typeName;
}


// Naming (rust-contract.md §3: strip leading `wire.`, split on `.`, kebab →
// snake/Pascal per segment, joined with `_` / nothing)
// ---------------------------------------------------------------------------

function pascalSegment(segment) {
  return segment
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('');
}

function snakeOfId(id) {
  const segments = id.startsWith('wire.') ? id.slice('wire.'.length).split('.') : id.split('.');
  return segments.map((segment) => segment.replace(/-/g, '_')).join('_');
}

function pascalOfId(id) {
  const segments = id.startsWith('wire.') ? id.slice('wire.'.length).split('.') : id.split('.');
  return segments.map(pascalSegment).join('');
}

function snakeKey(key) {
  return key.replace(/([a-z0-9])([A-Z])/g, '$1_$2').toLowerCase();
}

/** PascalCase of a discriminated value or inline key, e.g. `consumer_lagged` → `ConsumerLagged`. */
function pascalValue(value) {
  return pascalSegment(value);
}

/** Rust string literal content (escapes backslashes and quotes). */
function rustStr(value) {
  return value.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
}

/** Rust numeric literal for a JSON number (f64 gets a `.0` suffix when integral). */
function rustNumber(value) {
  if (Number.isInteger(value)) return `${value}.0`;
  return String(value);
}

function isStringConst(member) {
  return (
    member !== null &&
    typeof member === 'object' &&
    member.type === 'string' &&
    typeof member.const === 'string'
  );
}


function buildOutputs(registry, wire) {
  const { operations, schemas } = registry;
  const fixtures = Array.isArray(registry.fixtures)
    ? registry.fixtures
    : wire.PRODUCT_WIRE_FIXTURES;
  if (!Array.isArray(fixtures)) {
    throw new Error(
      'wire layer exposes neither `buildProductWireRegistry().fixtures` nor ' +
        '`PRODUCT_WIRE_FIXTURES`; the WireFixture[] list is required to generate the corpus',
    );
  }
  const { compileWireContract, WIRE_PROTOCOL, SCHEMA_DIALECT, FFI_ABI_VERSION, GENERATOR_VERSION } =
    wire;
  // Re-run compilation as a sanity gate; it throws ContractCompileError on any violation.
  compileWireContract({ operations, fixtures }, schemas);

  const bundle = {
    wireProtocol: WIRE_PROTOCOL,
    schemaDialect: SCHEMA_DIALECT,
    schemas: [...schemas.values()],
    operations,
  };
  const bundleText = canonicalString(bundle) + '\n';
  const schemaHash = createHash('sha256').update(bundleText, 'utf8').digest('hex');

  const manifest = {
    wireProtocol: WIRE_PROTOCOL,
    schemaDialect: SCHEMA_DIALECT,
    schemaHash,
    ffiAbiVersion: FFI_ABI_VERSION,
    generatorVersion: GENERATOR_VERSION,
    operations: Object.fromEntries(
      operations.map((op) => [
        op.operationId,
        {
          feature: op.feature,
          version: op.version,
          executionClass: op.executionClass,
          idempotency: op.idempotency,
          retryPolicy: op.retryPolicy,
          authScope: op.authScope,
          requestSchemaId: op.requestSchemaId,
          ...(op.responseSchemaId !== undefined ? { responseSchemaId: op.responseSchemaId } : {}),
          ...(op.eventSchemaId !== undefined ? { eventSchemaId: op.eventSchemaId } : {}),
          allowedErrorCodes: op.allowedErrorCodes,
          requestLimitBytes: op.requestLimitBytes,
          responseLimitBytes: op.responseLimitBytes,
          ...(op.eventLimitBytes !== undefined ? { eventLimitBytes: op.eventLimitBytes } : {}),
          unknownFields: op.unknownFields,
        },
      ]),
    ),
  };

  const corpus = fixtures.map((fixture) => ({
    id: fixture.id,
    operationId: fixture.operationId,
    kind: fixture.kind,
    schemaId: wire.resolveFixtureSchemaId(fixture, operations),
    valid: fixture.valid,
    file: `${fixture.id}.json`,
  }));

  const outputs = {};
  outputs['packages/contracts/generated/contract.bundle.json'] = bundleText;
  outputs['packages/contracts/generated/contract-manifest.json'] = canonicalString(manifest) + '\n';
  outputs['packages/contracts/generated/fixtures/corpus.json'] = canonicalString(corpus) + '\n';
  for (const fixture of fixtures) {
    outputs[`packages/contracts/generated/fixtures/${fixture.id}.json`] =
      canonicalString(fixture.value) + '\n';
  }
  const registryIds = new Set(schemas.keys());
  outputs['crates/contracts-generated/src/generated.rs'] = emitGeneratedRs(
    registryIds,
    operations,
    schemas.values(),
    wire.WIRE_FORMAT_PATTERNS,
  );
  return outputs;
}


/**
 * Expression for passing a path into `join_path(path: &str, key: &str)`: the root `path`
 * parameter is already `&str`; locals (`child_path`/`key_path`/`item_path`) are `String`
 * and must be borrowed explicitly (no auto-ref coercion at call sites).
 */
function joinPathExpr(p, keyExpr) {
  return p === 'path' ? `join_path(path, ${keyExpr})` : `join_path(&${p}, ${keyExpr})`;
}

/**
 * Expression for a path passed to `Issue::new(impl Into<String>, ...)`: the root `path`
 * parameter is `&str` (cheap, Into<String> works); local `String`s must be borrowed via
 * `as_str()` or each use would move them (E0382).
 */
function issuePathExpr(p) {
  return p === 'path' ? p : `${p}.as_str()`;
}

/** Register a regex static for the current check fn; returns its name (RE_<n>). */
function ensureRegex(pattern, ctx) {
  const name = `RE_${ctx.staticIndex.n++}`;
  ctx.statics.push({ name, pattern });
  return name;
}

function emitNodeCheck(schema, v, p, ctx, ind, isRoot = false) {
  if (schema === null || typeof schema !== 'object') {
    throw new Error(`checker: expected a schema object, got ${String(schema)}`);
  }
  if (!isRoot && typeof schema.$id === 'string' && ctx.registryIds.has(schema.$id)) {
    return [`${ind}check_${snakeOfId(schema.$id)}(${v}, &${p}, issues);`];
  }
  if (Array.isArray(schema.anyOf)) {
    if (schema.anyOf.every(isStringConst)) return emitEnumCheck(schema, v, p, ind);
    if (typeof schema['x-wire-discriminator'] === 'string' && schema['x-wire-discriminator']) {
      return emitDiscriminatedCheck(schema, v, p, ctx, ind);
    }
    throw new Error(
      `checker: unsupported anyOf (not a closed string enum, no discriminator): ${canonicalString(schema)}`,
    );
  }
  switch (schema.type) {
    case 'string':
      return emitStringCheck(schema, v, p, ctx, ind);
    case 'integer':
      return emitIntegerCheck(schema, v, p, ind);
    case 'number':
      return emitNumberCheck(schema, v, p, ind);
    case 'boolean':
      return [
        `${ind}if !${v}.is_boolean() {`,
        `${ind}    issues.push(Issue::new(${issuePathExpr(p)}, "Boolean"));`,
        `${ind}}`,
      ];
    case 'null':
      return [
        `${ind}if !${v}.is_null() {`,
        `${ind}    issues.push(Issue::new(${issuePathExpr(p)}, "Null"));`,
        `${ind}}`,
      ];
    case 'object':
      return emitObjectCheck(schema, v, p, ctx, ind);
    case 'array':
      return emitArrayCheck(schema, v, p, ctx, ind);
    default:
      throw new Error(
        `checker: unsupported schema type ${JSON.stringify(schema.type)}: ${canonicalString(schema)}`,
      );
  }
}

function emitStringCheck(schema, v, p, ctx, ind) {
  const ind1 = ind + '    ';
  const ind2 = ind + '        ';
  const hasMinLength = typeof schema.minLength === 'number' && schema.minLength > 0;
  const hasMaxLength = typeof schema.maxLength === 'number';
  const inner = [];
  if (hasMinLength) {
    inner.push(
      `${ind2}if len < ${schema.minLength} {`,
      `${ind2}    issues.push(Issue::new(${issuePathExpr(p)}, "StringMinLength"));`,
      `${ind2}}`,
    );
  }
  if (hasMaxLength) {
    inner.push(
      `${ind2}if len > ${schema.maxLength} {`,
      `${ind2}    issues.push(Issue::new(${issuePathExpr(p)}, "StringMaxLength"));`,
      `${ind2}}`,
    );
  }
  if (typeof schema.pattern === 'string') {
    const re = ensureRegex(schema.pattern, ctx);
    inner.push(
      `${ind2}if !${re}.is_match(s) {`,
      `${ind2}    issues.push(Issue::new(${issuePathExpr(p)}, "StringPattern"));`,
      `${ind2}}`,
    );
  }
  if (typeof schema.format === 'string') {
    const pattern = ctx.formatPatterns[schema.format];
    if (typeof pattern !== 'string') {
      throw new Error(`checker: unregistered wire format "${schema.format}"`);
    }
    const re = ensureRegex(pattern, ctx);
    inner.push(
      `${ind2}if !${re}.is_match(s) {`,
      `${ind2}    issues.push(Issue::new(${issuePathExpr(p)}, "StringFormat"));`,
      `${ind2}}`,
    );
  }
  if (typeof schema.const === 'string') {
    inner.push(
      `${ind2}if s != ${JSON.stringify(schema.const)} {`,
      `${ind2}    issues.push(Issue::new(${issuePathExpr(p)}, "StringConst"));`,
      `${ind2}}`,
    );
  }
  const lines = [
    `${ind}match ${v}.as_str() {`,
    `${ind1}Some(${inner.length > 0 ? 's' : '_s'}) => {`,
  ];
  if (inner.length > 0) {
    if (hasMinLength || hasMaxLength) {
      lines.push(`${ind2}let len = s.encode_utf16().count();`);
    }
    lines.push(...inner);
  }
  lines.push(
    `${ind1}}`,
    `${ind1}None => issues.push(Issue::new(${issuePathExpr(p)}, "String")),`,
    `${ind}}`,
  );
  return lines;
}


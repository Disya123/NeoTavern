function writeAtomic(absPath, content) {
  const tmpPath = `${absPath}.tmp-${process.pid}`;
  writeFileSync(tmpPath, content, 'utf8');
  try {
    renameSync(tmpPath, absPath);
  } catch (err) {
    // Windows: rename over an existing file is rejected; replace it first.
    if (err && (err.code === 'EPERM' || err.code === 'EEXIST')) {
      rmSync(absPath, { force: true });
      renameSync(tmpPath, absPath);
    } else {
      throw err;
    }
  }
}

/** 64-hex `WIRE_SCHEMA_HASH` literal from packages/contracts/src/wire/manifest.ts, or null. */
function readWireSchemaHash() {
  const tsPath = join(REPO_ROOT, 'packages', 'contracts', 'src', 'wire', 'manifest.ts');
  if (!existsSync(tsPath)) return null;
  const match = /WIRE_SCHEMA_HASH\s*=\s*['"]([0-9a-fA-F]{64})['"]/.exec(
    readFileSync(tsPath, 'utf8'),
  );
  return match ? match[1].toLowerCase() : null;
}

async function main() {
  const args = process.argv.slice(2);
  const checkOnly = args.includes('--check');
  const unknown = args.filter((arg) => arg !== '--check');
  if (unknown.length > 0) {
    console.error(
      `[contract-codegen] usage: node codegen.mjs [--check] (unknown args: ${unknown.join(' ')})`,
    );
    process.exit(2);
  }

  console.log('[contract-codegen] building @neotavern/contracts wire layer…');
  execSync('pnpm --filter @neotavern/contracts build', { cwd: REPO_ROOT, stdio: 'inherit' });

  const wire = await import(pathToFileURL(WIRE_INDEX).href);
  const requiredExports = [
    'buildProductWireRegistry',
    'compileWireContract',
    'resolveFixtureSchemaId',
    'WIRE_PROTOCOL',
    'SCHEMA_DIALECT',
    'FFI_ABI_VERSION',
    'GENERATOR_VERSION',
    'WIRE_FORMAT_PATTERNS',
  ];
  const missing = requiredExports.filter((name) => wire[name] === undefined);
  if (missing.length > 0) {
    throw new Error(`wire dist missing required exports: ${missing.join(', ')}`);
  }
  if (typeof wire.WIRE_FORMAT_PATTERNS !== 'object' || wire.WIRE_FORMAT_PATTERNS === null) {
    throw new Error('wire dist WIRE_FORMAT_PATTERNS must be an object');
  }

  const registry = wire.buildProductWireRegistry();
  const outputs = buildOutputs(registry, wire);

  const computedHash = JSON.parse(
    outputs['packages/contracts/generated/contract-manifest.json'],
  ).schemaHash;
  const sourceHash = readWireSchemaHash();
  const hashOk = sourceHash !== null && sourceHash === computedHash;
  const hashDetail =
    sourceHash === null
      ? 'WIRE_SCHEMA_HASH literal not found in packages/contracts/src/wire/manifest.ts'
      : `manifest.ts WIRE_SCHEMA_HASH ${sourceHash} != generated ${computedHash}`;

  if (checkOnly) {
    let failed = false;
    for (const [relPath, content] of Object.entries(outputs)) {
      const absPath = join(REPO_ROOT, relPath);
      let same = false;
      if (existsSync(absPath)) {
        same = readFileSync(absPath, 'utf8') === content;
      }
      console.log(`${same ? 'OK' : 'DIFF'} ${relPath}`);
      if (!same) failed = true;
    }
    if (hashOk) {
      console.log('OK packages/contracts/src/wire/manifest.ts (WIRE_SCHEMA_HASH matches)');
    } else {
      console.log(`DIFF packages/contracts/src/wire/manifest.ts (${hashDetail})`);
      failed = true;
    }
    const summary = failed
      ? '[contract-codegen] --check FAILED: outputs differ from disk'
      : '[contract-codegen] --check OK: outputs match disk';
    console.log(summary);
    process.exit(failed ? 1 : 0);
  }

  for (const [relPath, content] of Object.entries(outputs)) {
    const absPath = join(REPO_ROOT, relPath);
    mkdirSync(dirname(absPath), { recursive: true });
    writeAtomic(absPath, content);
    console.log(`[contract-codegen] wrote ${relPath}`);
  }
  if (!hashOk) {
    console.warn(`[contract-codegen] WARNING: ${hashDetail}`);
  }
  console.log('[contract-codegen] done.');
}

if (import.meta.main) {
  main().catch((err) => {
    console.error(`[contract-codegen] ${err && err.stack ? err.stack : String(err)}`);
    process.exit(1);
  });
}


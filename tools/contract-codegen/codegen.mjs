function emitStructLines(schema, typeName, ctx) {
  const props = schema.properties ?? {};
  const required = Array.isArray(schema.required) ? new Set(schema.required) : null;
  const ap = schema.additionalProperties;
  const tolerant = ap === true;
  const lines = ['#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]'];
  if (!tolerant) {
    lines.push('#[serde(deny_unknown_fields)]');
  }
  if (tolerant) {
    lines.push(`pub struct ${typeName} {`, '    pub payload: Value,', '}');
    return lines;
  }
  const fieldLines = [];
  for (const [key, prop] of Object.entries(props)) {
    const fieldName = rustFieldName(key);
    const optional = required === null || !required.has(key);
    const serdeOptions = [];
    if (snakeKey(key) !== key) serdeOptions.push(`rename = "${rustStr(key)}"`);
    if (optional) serdeOptions.push('default', 'skip_serializing_if = "Option::is_none"');
    const ty = rustTypeFor(prop, ctx, `${typeName}${pascalValue(key)}`);
    if (serdeOptions.length > 0) {
      fieldLines.push(`    #[serde(${serdeOptions.join(', ')})]`);
    }
    fieldLines.push(`    pub ${fieldName}: ${optional ? `Option<${ty}>` : ty},`);
  }
  if (fieldLines.length === 0) {
    lines.push(`pub struct ${typeName} {}`);
  } else {
    lines.push(`pub struct ${typeName} {`, ...fieldLines, '}');
  }
  return lines;
}

function emitEnumLines(schema, typeName) {
  const lines = [
    '#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]',
    `pub enum ${typeName} {`,
  ];
  for (const member of schema.anyOf) {
    lines.push(
      `    #[serde(rename = ${JSON.stringify(member.const)})] ${pascalValue(member.const)},`,
    );
  }
  lines.push('}');
  return lines;
}

function emitTaggedEnumLines(schema, typeName, ctx) {
  const disc = schema['x-wire-discriminator'];
  const lines = [
    '#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]',
    `#[serde(tag = "${disc}")]`,
    `pub enum ${typeName} {`,
  ];
  for (const member of schema.anyOf) {
    const constValue = member.properties[disc]?.const;
    if (typeof constValue !== 'string') {
      throw new Error(`tagged enum ${typeName}: member missing string const at "${disc}"`);
    }
    const fieldEntries = Object.entries(member.properties ?? {}).filter(([key]) => key !== disc);
    const variantName = pascalValue(constValue);
    if (fieldEntries.length === 0) {
      lines.push(`    #[serde(rename = ${JSON.stringify(constValue)})] ${variantName},`);
    } else {
      const required = Array.isArray(member.required) ? new Set(member.required) : null;
      const fields = fieldEntries.map(([key, prop]) => {
        const fieldName = rustFieldName(key);
        const serdeOptions = [];
        if (snakeKey(key) !== key) serdeOptions.push(`rename = "${rustStr(key)}"`);
        const optional = required === null || !required.has(key);
        if (optional) serdeOptions.push('default', 'skip_serializing_if = "Option::is_none"');
        const ty = rustTypeFor(prop, ctx, `${typeName}${pascalValue(key)}`);
        const attr = serdeOptions.length > 0 ? `#[serde(${serdeOptions.join(', ')})] ` : '';
        return `${attr}${fieldName}: ${optional ? `Option<${ty}>` : ty}`;
      });
      lines.push(
        `    #[serde(rename = ${JSON.stringify(constValue)})] ${variantName} { ${fields.join(', ')} },`,
      );
    }
  }
  lines.push('}');
  return lines;
}

function emitCheckerForSchema(schema, snakeName, ctx) {
  const fnCtx = { ...ctx, statics: [], staticIndex: { n: 0 } };
  const body = emitNodeCheck(schema, 'value', 'path', fnCtx, '    ', true);
  const statics = fnCtx.statics.map(
    (s) =>
      `static ${s.name}: LazyLock<Regex> = LazyLock::new(|| Regex::new("${rustStr(s.pattern)}").unwrap_or_else(|_| Regex::new("$^").unwrap()));`,
  );
  return [
    `pub(crate) fn check_${snakeName}(value: &Value, path: &str, issues: &mut Vec<Issue>) {`,
    ...statics.map((line) => `    ${line}`),
    ...body,
    '}',
  ];
}

function emitValidateDecode(snakeName, typeName) {
  return [
    `pub fn validate_${snakeName}(value: &Value) -> Result<(), Vec<Issue>> {`,
    '    let mut issues = Vec::new();',
    `    check_${snakeName}(value, "", &mut issues);`,
    '    if issues.is_empty() { Ok(()) } else { Err(issues) }',
    '}',
    '',
    `pub fn decode_${snakeName}(bytes: &[u8]) -> Result<${typeName}, WireError> {`,
    `    crate::decode::<${typeName}>(validate_${snakeName}, bytes)`,
    '}',
  ];
}

function emitTopLevelSchema(schema, ctx) {
  const id = schema.$id;
  if (typeof id !== 'string' || id.length === 0) {
    throw new Error(`registry schema without $id: ${canonicalString(schema)}`);
  }
  const snakeName = snakeOfId(id);
  const typeName = pascalOfId(id);
  const lines = [];
  if (Array.isArray(schema.anyOf)) {
    if (schema.anyOf.every(isStringConst)) {
      lines.push(...emitEnumLines(schema, typeName));
    } else if (
      typeof schema['x-wire-discriminator'] === 'string' &&
      schema['x-wire-discriminator']
    ) {
      lines.push(...emitTaggedEnumLines(schema, typeName, ctx));
    } else {
      throw new Error(`registry schema ${id}: unsupported anyOf shape`);
    }
  } else if (schema.type === 'object') {
    lines.push(...emitStructLines(schema, typeName, ctx));
  } else {
    throw new Error(
      `registry schema ${id}: unsupported top-level type ${JSON.stringify(schema.type)}`,
    );
  }
  lines.push(
    '',
    ...emitCheckerForSchema(schema, snakeName, ctx),
    '',
    ...emitValidateDecode(snakeName, typeName),
  );
  if (id === 'wire.error.dto') {
    // Alias matching the wire-design export name ProductErrorDto ($id wire.error.dto).
    lines.push(
      '',
      '/// Alias for `ErrorDto` (wire-design name for `wire.error.dto`).',
      'pub type ProductErrorDto = ErrorDto;',
    );
  }
  if (id === 'wire.request.empty') {
    // Kernel dispatch contract (rust-contract.md §5) references decode_empty_request_dto.
    lines.push(
      '',
      '/// Kernel-contract alias for `decode_request_empty`.',
      'pub fn decode_empty_request_dto(bytes: &[u8]) -> Result<RequestEmpty, WireError> {',
      '    crate::decode::<RequestEmpty>(validate_request_empty, bytes)',
      '}',
    );
  }
  if (id === 'wire.result.empty') {
    lines.push(
      '',
      '/// Kernel-contract alias for `decode_result_empty`.',
      'pub fn decode_empty_result_dto(bytes: &[u8]) -> Result<ResultEmpty, WireError> {',
      '    crate::decode::<ResultEmpty>(validate_result_empty, bytes)',
      '}',
    );
  }
  return lines;
}

function emitGeneratedRs(registryIds, operations, schemas, formatPatterns) {
  const ctx = {
    registryIds,
    formatPatterns,
    helpers: [],
    staticIndex: { n: 0 },
    statics: [],
  };
  const mainBlocks = [];
  for (const schema of schemas) {
    mainBlocks.push(emitTopLevelSchema(schema, ctx).join('\n'));
  }
  const helperBlocks = ctx.helpers.map((helper) => helper.structLines.join('\n'));
  const joinPath = [
    'fn join_path(path: &str, key: &str) -> String {',
    '    format!("{}{}{}", path, if path.is_empty() { "" } else { "/" }, key)',
    '}',
  ].join('\n');
  return [
    HEADER.trimEnd(),
    joinPath,
    emitLimits(operations),
    ...helperBlocks,
    ...mainBlocks,
  ].join('\n\n') + '\n';
}

/**
 * Emits the per-operation byte limits as generated Rust (plan rev 2.2
 * Layer C): `operation_request_limit` / `operation_response_limit` plus the
 * registry-wide maxima used as defaults. Single source of truth — the
 * numbers come from the registry here, exactly like the manifest, so no
 * hand-written 1 MiB / 16 MiB constants can drift.
 */
function emitLimits(operations) {
  const reqMax = Math.max(...operations.map((op) => op.requestLimitBytes));
  const respMax = Math.max(...operations.map((op) => op.responseLimitBytes));
  const reqLines = operations.map((op) => `        "${op.operationId}" => Some(${op.requestLimitBytes}),`);
  const respLines = operations.map((op) => `        "${op.operationId}" => Some(${op.responseLimitBytes}),`);
  return [
    '/// The maximum request byte limit across the registry (generated).',
    `pub const DEFAULT_REQUEST_LIMIT_BYTES: u64 = ${reqMax};`,
    '/// The maximum response byte limit across the registry (generated).',
    `pub const DEFAULT_RESPONSE_LIMIT_BYTES: u64 = ${respMax};`,
    '',
    '/// The wire request byte limit for `operation_id` (generated from the',
    '/// registry; `None` for an operation that is not part of the contract).',
    'pub fn operation_request_limit(operation_id: &str) -> Option<u64> {',
    '    match operation_id {',
    ...reqLines,
    '        _ => None,',
    '    }',
    '}',
    '',
    '/// The wire response byte limit for `operation_id` (generated from the',
    '/// registry; `None` for an operation that is not part of the contract).',
    'pub fn operation_response_limit(operation_id: &str) -> Option<u64> {',
    '    match operation_id {',
    ...respLines,
    '        _ => None,',
    '    }',
    '}',
  ].join('\n');
}


/**
 * Recursively sort object keys (arrays keep order), reject values that cannot be
 * represented deterministically, and return a plain JSON-ready structure.
 */
function sortJson(value) {
  if (value === null || typeof value === 'string' || typeof value === 'boolean') {
    return value;
  }
  if (typeof value === 'number') {
    if (!Number.isFinite(value)) {
      throw new Error(`canonical JSON: non-finite number ${value} is not wire-safe`);
    }
    return value;
  }
  if (Array.isArray(value)) {
    return value.map((item) => {
      if (item === undefined) {
        throw new Error('canonical JSON: undefined inside an array is not wire-safe');
      }
      return sortJson(item);
    });
  }
  if (typeof value === 'object') {
    const out = {};
    for (const key of Object.keys(value).sort()) {
      const item = value[key];
      if (item === undefined) continue;
      out[key] = sortJson(item);
    }
    return out;
  }
  throw new Error(`canonical JSON: unsupported value of type ${typeof value}`);
}

/** Canonical JSON string: recursively key-sorted, no whitespace. */
function canonicalString(value) {
  return JSON.stringify(sortJson(value));
}


function emitObjectCheck(schema, v, p, ctx, ind) {
  const ind1 = ind + '    ';
  const ind2 = ind + '        ';
  const ind3 = ind + '            ';
  const props = schema.properties ?? {};
  const keys = Object.keys(props);
  const ap = schema.additionalProperties;
  const tolerant = ap === true;
  const mapSchema = ap !== null && typeof ap === 'object' ? ap : null;
  const required = Array.isArray(schema.required) ? schema.required : [];
  const lines = [
    `${ind}if !${v}.is_object() {`,
    `${ind1}issues.push(Issue::new(${issuePathExpr(p)}, "Object"));`,
    `${ind}} else {`,
  ];
  if (tolerant) {
    lines.push(`${ind}}`);
    return lines;
  }
  if (mapSchema) {
    lines.push(
      `${ind1}if let Some(obj) = ${v}.as_object() {`,
      `${ind2}for (key, val) in obj {`,
      `${ind3}let key_path = ${joinPathExpr(p, 'key')};`,
      ...emitNodeCheck(mapSchema, 'val', 'key_path', ctx, ind3),
      `${ind2}}`,
      `${ind1}}`,
      `${ind}}`,
    );
    return lines;
  }
  for (const key of required) {
    if (!props[key]) {
      throw new Error(
        `checker: required key "${key}" is not a property of ${canonicalString(schema)}`,
      );
    }
    lines.push(
      `${ind1}if ${v}.get(${JSON.stringify(key)}).is_none() {`,
      `${ind2}issues.push(Issue::new(${joinPathExpr(p, JSON.stringify(key))}, "RequiredProperty"));`,
      `${ind1}}`,
    );
  }
  for (const key of keys) {
    lines.push(
      `${ind1}if let Some(child) = ${v}.get(${JSON.stringify(key)}) {`,
      `${ind2}let child_path = ${joinPathExpr(p, JSON.stringify(key))};`,
      ...emitNodeCheck(props[key], 'child', 'child_path', ctx, ind2),
      `${ind1}}`,
    );
  }
  lines.push(`${ind1}if let Some(obj) = ${v}.as_object() {`, `${ind2}for key in obj.keys() {`);
  if (keys.length === 0) {
    // Empty strict object: every present key is unknown.
    lines.push(
      `${ind3}let key_path = ${joinPathExpr(p, 'key')};`,
      `${ind3}issues.push(Issue::new(key_path.as_str(), "AdditionalProperties"));`,
    );
  } else {
    lines.push(
      `${ind3}if !matches!(key.as_str(), ${keys.map((key) => JSON.stringify(key)).join(' | ')}) {`,
      `${ind3}    let key_path = ${joinPathExpr(p, 'key')};`,
      `${ind3}    issues.push(Issue::new(key_path.as_str(), "AdditionalProperties"));`,
      `${ind3}}`,
    );
  }
  lines.push(`${ind2}}`, `${ind1}}`, `${ind}}`);
  return lines;
}

function emitArrayCheck(schema, v, p, ctx, ind) {
  const ind1 = ind + '    ';
  const ind2 = ind + '        ';
  const items = schema.items;
  if (items === null || typeof items !== 'object') {
    throw new Error(`checker: array without an items schema: ${canonicalString(schema)}`);
  }
  const lines = [
    `${ind}if !${v}.is_array() {`,
    `${ind1}issues.push(Issue::new(${issuePathExpr(p)}, "Array"));`,
    `${ind}} else if let Some(arr) = ${v}.as_array() {`,
  ];
  if (typeof schema.minItems === 'number') {
    lines.push(
      `${ind1}if arr.len() < ${schema.minItems} {`,
      `${ind2}issues.push(Issue::new(${issuePathExpr(p)}, "ArrayMinItems"));`,
      `${ind1}}`,
    );
  }
  if (typeof schema.maxItems === 'number') {
    lines.push(
      `${ind1}if arr.len() > ${schema.maxItems} {`,
      `${ind2}issues.push(Issue::new(${issuePathExpr(p)}, "ArrayMaxItems"));`,
      `${ind1}}`,
    );
  }
  lines.push(
    `${ind1}for (i, item) in arr.iter().enumerate() {`,
    `${ind2}let item_path = format!("{}[{}]", ${p}, i);`,
    ...emitNodeCheck(items, 'item', 'item_path', ctx, ind2),
    `${ind1}}`,
    `${ind}}`,
  );
  return lines;
}

function emitEnumCheck(schema, v, p, ind) {
  const ind1 = ind + '    ';
  const ind2 = ind + '        ';
  const ind3 = ind + '            ';
  const values = schema.anyOf.map((member) => member.const);
  return [
    `${ind}match ${v}.as_str() {`,
    `${ind1}Some(s) => {`,
    `${ind2}if !matches!(s, ${values.map((value) => JSON.stringify(value)).join(' | ')}) {`,
    `${ind3}issues.push(Issue::new(${issuePathExpr(p)}, "Union"));`,
    `${ind2}}`,
    `${ind1}}`,
    `${ind1}None => issues.push(Issue::new(${issuePathExpr(p)}, "String")),`,
    `${ind}}`,
  ];
}


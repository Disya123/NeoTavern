/**
 * Recursively sort object keys (arrays keep order), reject values that cannot be
 * represented deterministically, and return a plain JSON-ready structure.
 */
function emitDiscriminatedCheck(schema, v, p, ctx, ind) {
  const ind1 = ind + '    ';
  const ind2 = ind + '        ';
  const ind3 = ind + '            ';
  const disc = schema['x-wire-discriminator'];
  const lines = [
    `${ind}let tag = ${v}.get(${JSON.stringify(disc)}).and_then(|t| t.as_str());`,
    `${ind}match tag {`,
  ];
  for (const member of schema.anyOf) {
    if (member === null || typeof member !== 'object' || typeof member.properties !== 'object') {
      throw new Error(
        `checker: discriminator member is not an object schema: ${canonicalString(member)}`,
      );
    }
    const constValue = member.properties[disc]?.const;
    if (typeof constValue !== 'string') {
      throw new Error(
        `checker: discriminator member missing string const at "${disc}": ${canonicalString(member)}`,
      );
    }
    const props = member.properties;
    const memberKeys = Object.keys(props);
    const checkKeys = memberKeys.filter((key) => key !== disc);
    const memberRequired = Array.isArray(member.required) ? member.required : [];
    const required = memberRequired.filter((key) => key !== disc);
    lines.push(`${ind1}Some(${JSON.stringify(constValue)}) => {`);
    for (const key of required) {
      if (!props[key]) {
        throw new Error(`checker: discriminator member requires unknown key "${key}"`);
      }
      lines.push(
        `${ind2}if ${v}.get(${JSON.stringify(key)}).is_none() {`,
        `${ind3}issues.push(Issue::new(${joinPathExpr(p, JSON.stringify(key))}, "RequiredProperty"));`,
        `${ind2}}`,
      );
    }
    for (const key of checkKeys) {
      lines.push(
        `${ind2}if let Some(child) = ${v}.get(${JSON.stringify(key)}) {`,
        `${ind3}let child_path = ${joinPathExpr(p, JSON.stringify(key))};`,
        ...emitNodeCheck(props[key], 'child', 'child_path', ctx, ind3),
        `${ind2}}`,
      );
    }
    lines.push(`${ind2}if let Some(obj) = ${v}.as_object() {`, `${ind3}for key in obj.keys() {`);
    if (memberKeys.length === 0) {
      lines.push(
        `${ind3}    let key_path = ${joinPathExpr(p, 'key')};`,
        `${ind3}    issues.push(Issue::new(key_path.as_str(), "AdditionalProperties"));`,
      );
    } else {
      lines.push(
        `${ind3}    if !matches!(key.as_str(), ${memberKeys.map((key) => JSON.stringify(key)).join(' | ')}) {`,
        `${ind3}        let key_path = ${joinPathExpr(p, 'key')};`,
        `${ind3}        issues.push(Issue::new(key_path.as_str(), "AdditionalProperties"));`,
        `${ind3}    }`,
      );
    }
    lines.push(`${ind3}}`, `${ind2}}`, `${ind1}}`);
  }
  lines.push(
    `${ind1}_ => issues.push(Issue::new(${issuePathExpr(p)}, "Discriminator")),`,
    `${ind}}`,
  );
  return lines;
}


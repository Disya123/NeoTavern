/** Recursively widen literal types to `string` so other locales can provide
 * their own text while being forced to match the exact key structure. */
type DeepWiden<T> = T extends string
  ? string
  : T extends readonly (infer U)[]
    ? DeepWiden<U>[]
    : { [K in keyof T]: DeepWiden<T[K]> };

export type Resources = DeepWiden<typeof en>;
